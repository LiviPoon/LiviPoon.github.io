#!/usr/bin/env node
// Regenerates site/data/site-data.js from the habit logs and mirror quotes.
//   node tools/build-data.mjs
// No dependencies. Run it after editing data/habits/*.md or data/mirror-quotes.json
// (the deploy workflow also runs it before publishing).
//
// Output: a tiny script that fills the hidden #quartz-body element's data attributes,
// which roll-counter.js, habit-timeline.js and app.js read from.

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const habitsDir = path.join(root, "data", "habits")
const quotesPath = path.join(root, "data", "mirror-quotes.json")
const outPath = path.join(root, "site", "data", "site-data.js")

const DONE = new Set(["1", "true", "yes", "y", "x", "done", "complete", "completed", "checked"])
const isDone = (raw) => {
  const v = raw.trim().toLowerCase()
  if (!v) return false
  const n = Number(v)
  return Number.isNaN(n) ? DONE.has(v) : n > 0
}
const validDate = (s) => /^\d{4}-\d{2}-\d{2}$/.test(s) && !Number.isNaN(Date.parse(`${s}T00:00:00Z`))
const iso = (d) => d.toISOString().slice(0, 10)
const weekStart = (d) => {
  const s = new Date(d)
  s.setUTCDate(s.getUTCDate() - ((s.getUTCDay() + 6) % 7))
  return s
}

// A habit file lists completed dates as "- YYYY-MM-DD" (frontmatter `entries:` or body),
// a bare "YYYY-MM-DD" line, or "YYYY-MM-DD, <value>" CSV rows.
function completedDates(text) {
  const dates = new Set()
  for (const line of text.split(/\r?\n/)) {
    const csv = line.match(/^(\d{4}-\d{2}-\d{2})\s*,\s*(.+)$/)
    if (csv) {
      if (validDate(csv[1]) && isDone(csv[2])) dates.add(csv[1])
      continue
    }
    const single = line.match(/^\s*(?:-\s*)?(\d{4}-\d{2}-\d{2})\s*$/)
    if (single && validDate(single[1])) dates.add(single[1])
  }
  return dates
}

function habitData() {
  if (!fs.existsSync(habitsDir)) return { timeline: [], weeklySeries: [] }
  const habits = fs
    .readdirSync(habitsDir)
    .filter((f) => f.toLowerCase().endsWith(".md"))
    .map((f) => ({
      habit: path.basename(f, path.extname(f)),
      dates: completedDates(fs.readFileSync(path.join(habitsDir, f), "utf8")),
    }))
    .sort((a, b) => a.habit.localeCompare(b.habit))

  const daily = new Map()
  for (const h of habits) for (const d of h.dates) daily.set(d, (daily.get(d) ?? 0) + 1)
  if (daily.size === 0) return { timeline: [], weeklySeries: [] }

  const sorted = [...daily.keys()].sort()
  const first = new Date(`${sorted[0]}T00:00:00Z`)
  const last = new Date(`${sorted.at(-1)}T00:00:00Z`)

  const timeline = []
  for (const c = new Date(first); c <= last; c.setUTCDate(c.getUTCDate() + 1)) {
    timeline.push({ date: iso(c), count: daily.get(iso(c)) ?? 0 })
  }

  const weeks = []
  for (const c = weekStart(first); c <= weekStart(last); c.setUTCDate(c.getUTCDate() + 7)) {
    weeks.push(iso(c))
  }
  const weeklySeries = habits.map(({ habit, dates }) => {
    const perWeek = new Map()
    for (const d of dates) {
      const w = iso(weekStart(new Date(`${d}T00:00:00Z`)))
      perWeek.set(w, (perWeek.get(w) ?? 0) + 1)
    }
    return {
      habit,
      averagePerWeek: dates.size / Math.max(1, weeks.length),
      weekly: weeks.map((w) => ({ weekStart: w, count: perWeek.get(w) ?? 0 })),
    }
  })
  return { timeline, weeklySeries }
}

function boldQuotes() {
  if (!fs.existsSync(quotesPath)) return []
  return JSON.parse(fs.readFileSync(quotesPath, "utf8"))
    .filter((q) => q["make-bold"] === true)
    .map((q) => ({ text: String(q.text ?? ""), speaker: String(q.speaker ?? ""), role: String(q.role ?? "") }))
}

const { timeline, weeklySeries } = habitData()
const data = {
  habitTimeline: JSON.stringify(timeline),
  habitWeeklySeries: JSON.stringify(weeklySeries),
  mirrorBoldQuotes: JSON.stringify(boldQuotes()),
}
const js = `// Generated by tools/build-data.mjs — do not edit by hand.
;(function () {
  var el = document.getElementById("quartz-body")
  if (!el) return
  var data = ${JSON.stringify(data, null, 2)}
  for (var key in data) el.dataset[key] = data[key]
})()
`
fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, js)
console.log(`wrote ${path.relative(root, outPath)} (${timeline.length} days, ${weeklySeries.length} habits)`)
